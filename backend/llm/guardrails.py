def enforce_guardrails(llm_response: str) -> str:
    """
    Enforces terminology guardrails on the LLM output.
    The LLM must not act as a doctor, must not use definitive diagnosis terms.
    Always appends a fixed clinical support disclaimer footer.
    """
    replacements = {
        r"\bdiagnose\b": "screen",
        r"\bdiagnosed\b": "screened",
        r"\bdiagnosed with\b": "screened positive for",
        r"\bdiagnosis\b": "screening result",
        r"\bdiagnoses\b": "screening results",
        r"\byou have tuberculosis\b": "the image is suspicious for tuberculosis",
        r"\byou do not have tuberculosis\b": "the image is not suspicious for tuberculosis",
        r"\bconfirmed\b": "suspected",
        r"\bdefinitely\b": "potentially",
        r"\bthis is tuberculosis\b": "this is suspicious for tuberculosis",
        r"\bis tuberculosis\b": "is suspicious for tuberculosis",
        r"\bhas tuberculosis\b": "shows features suspicious for tuberculosis",
        r"\bhave tuberculosis\b": "shows features suspicious for tuberculosis",
        r"\bcertainly\b": "potentially",
        r"\babsolute certainty\b": "high suspicion",
        r"\bproves\b": "suggests",
        r"\bclear evidence of\b": "findings consistent with"
    }
    
    # Run replacements case-insensitively using regex word boundaries
    import re
    for bad_pattern, good_term in replacements.items():
        pattern = re.compile(bad_pattern, re.IGNORECASE)
        llm_response = pattern.sub(good_term, llm_response)
            
    # Always append the fixed disclaimer footer
    disclaimer_footer = (
        "\n\n---\n"
        "**CLINICAL SUPPORT DISCLAIMER:** This report is generated by an AI-assisted screening model for clinical decision support "
        "and is not a definitive medical diagnosis. All findings and heatmaps must be clinically correlated and verified by a "
        "licensed medical practitioner or radiologist before initiating treatment. Confirmation should be established via laboratory "
        "microbiology (e.g. sputum AFB smear, GeneXpert, or Truenat molecular assay)."
    )
    
    # Strip any existing duplicate footer/disclaimer to prevent accumulation
    clean_response = llm_response.split("**CLINICAL SUPPORT DISCLAIMER:**")[0].strip()
    clean_response = clean_response.split("DISCLAIMER: This is an AI screening result")[0].strip()
    
    return clean_response + disclaimer_footer


