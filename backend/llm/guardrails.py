def enforce_guardrails(llm_response: str) -> str:
    """
    Enforces terminology guardrails on the LLM output.
    The LLM must not act as a doctor, must not use definitive diagnosis terms.
    """
    # Just a simple string replacement for now to demonstrate guardrails
    replacements = {
        "diagnosis": "screening result",
        "diagnosed with": "screened positive for",
        "you have tuberculosis": "the image is suspicious for tuberculosis",
        "you do not have tuberculosis": "the image is not suspicious for tuberculosis",
        "definitely": "potentially"
    }
    # A simple string replacement
    for bad_term, good_term in replacements.items():
        # Case insensitive replacement via a basic approach
        import re
        pattern = re.compile(re.escape(bad_term), re.IGNORECASE)
        llm_response = pattern.sub(good_term, llm_response)
            
    # For now, just prepend a disclaimer if not present
    disclaimer = "DISCLAIMER: This is an AI screening result, not a definitive medical diagnosis. "
    if disclaimer not in llm_response:
        return disclaimer + llm_response
        
    return llm_response

